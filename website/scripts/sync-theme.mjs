// Copies the desktop app's light theme into the website, so both share one palette and radius.
//
// The app defines its HeroUI tokens in src/renderer/styles.css: the light block first (`:root,
// .light, ...`), then its own derived tokens (`--primary-light`, the radii). This copies both,
// unchanged, to src/styles/app-theme.css, which globals.css imports and maps its own names onto.
// The copy is committed, so a host that builds only this folder still works.
//
//   node scripts/sync-theme.mjs           write the copy
//   node scripts/sync-theme.mjs --check   fail when the copy differs from the desktop source

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const from = 'src/renderer/styles.css'
const source = join(here, '../..', from)
const target = join(here, '../src/styles/app-theme.css')
const check = process.argv.includes('--check')

if (!existsSync(source)) {
  // building from a checkout of this folder alone: keep the committed copy
  if (check) {
    console.error(`theme: ${source} not found, cannot check`)
    process.exit(1)
  }
  console.log('theme: desktop source not found, using the committed copy')
  process.exit(0)
}

const css = readFileSync(source, 'utf8')
// a top-level rule, from its selector to its closing brace at the start of a line
const block = (selector) => {
  const start = css.indexOf(selector)
  if (start < 0) throw new Error(`theme: "${selector}" not found in ${from}`)
  return css.slice(start, css.indexOf('\n}\n', start) + 3)
}
// the light tokens, and the app's own tokens without its page-level font, size and comments
const light = block(':root,\n.light,')
const own = block(':root {\n  --ink:')
  .split('\n')
  .filter((line) => /^\s*(--|:root|\})/.test(line))
  .join('\n')
  .concat('\n')
const output = `/* Generated by scripts/sync-theme.mjs from ${from}. Do not edit. */\n\n${light}\n${own}`

const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
if (check) {
  if (current !== output) {
    console.error('theme: src/styles/app-theme.css is out of date; run npm run sync:theme')
    process.exit(1)
  }
  console.log('theme: in step with the desktop app')
} else if (current !== output) {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, output)
  console.log('theme: wrote src/styles/app-theme.css')
}
